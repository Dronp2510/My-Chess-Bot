def evaluate_board(gs):

    # terminal positions
    if gs.checkmate:

        if gs.white_to_move:
            return -CHECKMATE
        else:
            return CHECKMATE

    elif gs.stalemate:
        return STALEMATE

    score = 0

    for row_index, row in enumerate(gs.board):
        for col_index, piece in enumerate(row):

            if piece == "--":
                continue

            piece_type = piece[1:]
            piece_value = (
                piece_score[piece_type]
                +
                get_piece_square_score(piece, row_index, col_index)
            )

            if piece[0] == 'w':
                score += piece_value

            else:
                score -= piece_value

    return score if gs.white_to_move else -score

def get_piece_square_score(piece, row, col):

    piece_type = piece[1:]
    table = piece_square_tables[piece_type]

    if piece[0] == 'w':
        return table[row][col]

    return table[7 - row][col]
